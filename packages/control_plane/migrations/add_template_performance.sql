-- Add comments for documentation
COMMENT ON TABLE template_performance_runs IS 'Historical backtest runs for strategy templates';
COMMENT ON COLUMN template_performance_runs.metrics IS 'Performance metrics: total_return, sharpe_ratio, max_drawdown, win_rate, equity_curve, etc.';

COMMENT ON TABLE template_signals IS 'Historical signals generated by templates with outcomes';
COMMENT ON COLUMN template_signals.pnl IS 'Profit/loss percentage for executed signals';

